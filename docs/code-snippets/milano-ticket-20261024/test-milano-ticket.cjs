const fs=require('fs'),vm=require('vm'),assert=require('assert');
const before=fs.readFileSync('milano-ticket-before.html','utf8');
const after=fs.readFileSync('milano-ticket-after.html','utf8');
const patches=JSON.parse(fs.readFileSync('milano-ticket-patches.json','utf8'));
const parser=new Function('heading',patches[0].new_content+'\nreturn title;');
assert.deepEqual(Array.from(parser({textContent:'Milano Sirki — Derince — 24 Ekim 2026 12:00'})).slice(1),Array.from(parser({textContent:'Milano Sirki — Derince — 2026-10-24 12:00'})).slice(1));
assert.equal(parser({textContent:'Milano Sirki — İzmir — 8 Kasım 2026 14:00'})[3],'11');
assert.equal(parser({textContent:'Milano Sirki — İzmir — 8 Kasım 2026 14:00'})[4],'08');
assert.equal(parser({textContent:'Beklenmeyen tarih'}),null);
const scripts=[...after.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
scripts.forEach(s=>new vm.Script(s));
const clarity=scripts.find(s=>s.includes('function sessionState'));
const fn=clarity.match(/function sessionState\(start, now\)\{[\s\S]*?\n  \}/)[0];
const state=new Function(fn+';return sessionState;')();
const start=Date.parse('2026-10-24T12:00:00+03:00');
assert.equal(state(start,start-1),'upcoming');
assert.equal(state(start,start),'started');
assert.equal(state(start,start+59*60000),'started');
assert.equal(state(start,start+60*60000),'ended');
assert.equal(state(NaN,start),'unknown');
const forms=h=>h.match(/<form\b[\s\S]*?<\/form>/g);
assert.deepEqual(forms(before),forms(after),'Do not change prices, IDs, quantities or checkout destination');
assert.equal((after.match(/<!-- wp:html -->/g)||[]).length,(after.match(/<!-- \/wp:html -->/g)||[]).length);
assert(!scripts.some(s=>s.includes('h<24')));
assert(after.includes('a[href="#darica"]'));
console.log('PASS: ISO/Turkish dates, invalid date fallback, 5 time boundaries, all scripts, unchanged checkout forms, block balance.');
